"""
figma_tokens.py
turns scripts/figma-variables.json into css custom properties, so the page reads
one list of colors, type and spacing instead of retyped hex codes. the sizes come from
the open skill 1 figma file's variables; the colors and fonts are david's field guide pick.

run: python scripts/figma_tokens.py   (writes css/tokens.css)
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
variables = json.loads((root / "scripts" / "figma-variables.json").read_text(encoding="utf-8"))["variables"]

fallbacks = {
    "font-display": '"Trebuchet MS", sans-serif',
    "font-reading": "Georgia, serif",
    "font-ui": '"Arial Narrow", Arial, sans-serif',
}

lines = [
    "/* generated by scripts/figma_tokens.py from scripts/figma-variables.json.",
    "   edit that json and rerun the script, not this file. */",
    ":root {",
]
for name, value in variables.items():
    # figma stores sizes as bare numbers, css needs px
    if name.startswith(("font-size", "font-line-height", "space", "radius")):
        value = f"{value}px"
    # the fallbacks keep the page readable if google fonts is slow
    if name in fallbacks:
        value = f'"{value}", {fallbacks[name]}'
    lines.append(f"  --{name}: {value};")
lines.append("}")

out = root / "css" / "tokens.css"
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {out.relative_to(root)} with {len(variables)} tokens")
